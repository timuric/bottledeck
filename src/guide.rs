//! Agent-facing usage guide, printable with `bottledeck agent-guide` and installable as a
//! Claude Code / Codex skill so agents learn the CLI without trial and error.

use crate::config::home_dir;
use anyhow::{Context, Result};
use std::path::{Path, PathBuf};

pub const AGENT_GUIDE: &str = include_str!("agent_guide.md");

const SKILL_NAME: &str = "bottledeck";
const SKILL_DESCRIPTION: &str = "Query local coding-agent telemetry with the bottledeck CLI. \
Use it to find what costs agents tokens, time or turns in a repo; check session by session whether a \
harness or repo fix worked; compare sessions before and after a commit or date; or audit failing \
commands and MCP tools. Applies to Claude Code, Codex, Antigravity and Kimi sessions.";
const VERSION_TAG: &str = "<!-- bottledeck-skill-version:";

/// The guide wrapped as a SKILL.md (frontmatter + version stamp + guide body).
pub fn skill_markdown(version: &str) -> String {
    format!(
        "---\nname: {SKILL_NAME}\ndescription: {SKILL_DESCRIPTION}\n---\n\n{VERSION_TAG} {version} -->\n\
         <!-- Generated by `bottledeck agent-guide --install`; re-run it after upgrading bottledeck. -->\n\n{AGENT_GUIDE}"
    )
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, clap::ValueEnum)]
pub enum SkillTarget {
    /// Every harness whose config directory exists (Claude Code if none do)
    All,
    /// Claude Code: $CLAUDE_CONFIG_DIR or ~/.claude
    Claude,
    /// Codex: $CODEX_HOME or ~/.codex
    Codex,
}

fn env_dir(var: &str) -> Option<PathBuf> {
    std::env::var_os(var)
        .filter(|v| !v.is_empty())
        .map(PathBuf::from)
}

pub fn claude_config_dir() -> PathBuf {
    env_dir("CLAUDE_CONFIG_DIR").unwrap_or_else(|| home_dir().join(".claude"))
}

pub fn codex_home_dir() -> PathBuf {
    env_dir("CODEX_HOME").unwrap_or_else(|| home_dir().join(".codex"))
}

fn skill_path(config_dir: &Path) -> PathBuf {
    config_dir.join("skills").join(SKILL_NAME).join("SKILL.md")
}

/// Every harness skill location, whether or not anything is installed there.
pub fn skill_locations() -> Vec<(&'static str, PathBuf)> {
    vec![
        ("claude-code", skill_path(&claude_config_dir())),
        ("codex", skill_path(&codex_home_dir())),
    ]
}

/// Skill files to write for a target. `All` picks harnesses whose config dir exists.
pub fn install_paths(target: SkillTarget) -> Vec<(&'static str, PathBuf)> {
    let claude = ("claude-code", skill_path(&claude_config_dir()));
    let codex = ("codex", skill_path(&codex_home_dir()));
    match target {
        SkillTarget::Claude => vec![claude],
        SkillTarget::Codex => vec![codex],
        SkillTarget::All => {
            let mut out = Vec::new();
            if claude_config_dir().is_dir() {
                out.push(claude);
            }
            if codex_home_dir().is_dir() {
                out.push(codex);
            }
            if out.is_empty() {
                out.push(("claude-code", skill_path(&claude_config_dir())));
            }
            out
        }
    }
}

pub fn write_skill(path: &Path, version: &str) -> Result<()> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)
            .with_context(|| format!("creating {}", parent.display()))?;
    }
    std::fs::write(path, skill_markdown(version))
        .with_context(|| format!("writing {}", path.display()))
}

/// Version stamp of an installed skill file, if it was written by bottledeck.
pub fn installed_skill_version(path: &Path) -> Option<String> {
    let text = std::fs::read_to_string(path).ok()?;
    let rest = &text[text.find(VERSION_TAG)? + VERSION_TAG.len()..];
    let end = rest.find("-->")?;
    Some(rest[..end].trim().to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn skill_has_frontmatter_and_round_trips_version() {
        let md = skill_markdown("9.9.9");
        assert!(md.starts_with("---\nname: bottledeck\ndescription: "));
        assert!(md.contains("## Time scoping"));
        let dir = tempfile::tempdir().unwrap();
        let p = dir.path().join("skills/bottledeck/SKILL.md");
        write_skill(&p, "9.9.9").unwrap();
        assert_eq!(installed_skill_version(&p).as_deref(), Some("9.9.9"));
    }

    #[test]
    fn guide_mentions_every_query_command() {
        for cmd in [
            "report",
            "inspect",
            "issues",
            "mark",
            "diff",
            "commands",
            "errors",
            "bypasses",
            "patterns",
            "sessions",
            "sequences",
            "tools",
            "repos",
            "sync",
        ] {
            assert!(
                AGENT_GUIDE.contains(&format!("`{cmd}"))
                    || AGENT_GUIDE.contains(&format!("bottledeck {cmd}")),
                "guide never mentions `{cmd}`"
            );
        }
    }
}
